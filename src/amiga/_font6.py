def _rows(pattern: str) -> list:
    assert len(pattern) == 35, pattern
    out = []
    for r in range(7):
        bits = 0
        for c in range(5):
            if pattern[r * 5 + c] == '#':
                bits |= 0x80 >> c
        out.append(bits)
    out.append(0)          # row 7 clear
    return out


FONT_6X8 = {ch: _rows(p) for ch, p in _GLYPHS.items()}
for _c in range(ord('a'), ord('z') + 1):
    FONT_6X8[chr(_c)] = FONT_6X8[chr(_c - 32)]

# Every code from 0x20 to 0x5A must have a glyph (C indexes the table by code)
for _code in range(0x20, 0x5B):
    assert chr(_code) in FONT_6X8, chr(_code)
